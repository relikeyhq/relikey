"""Docs as code: generate ReliKey's reference pages from their sources, and check every page.

The reference is never written by hand. It comes from where the facts live:
  - model/*.yaml           components and pins, contracts, flows, patterns, profiles
  - the agent's Go source  agent.json's fields (from their comments) and the subcommands' flags
  - each installer's own --help (argparse), and realm.py's usage

    python tools/docs.py generate      write docs/reference/*.md
    python tools/docs.py check         fail if a generated page is stale, a config field has no comment, or a relative
                                       link in the docs does not resolve

Every finding says what is wrong and what fixes it (decision 0001, failures say why).
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MODEL = ROOT / "model"
OUT = ROOT / "docs" / "reference"
AGENT_MAIN = ROOT / "agent" / "cmd" / "relikey-agent" / "main.go"
HEADER = "<!-- Generated by tools/docs.py from {src}. Do not edit: change the source and run `python tools/docs.py generate`. -->\n\n"
CLIS = [("deploy/core/install.py", "Install the shared core"), ("deploy/core/add_edge.py", "Register an edge at the core"),
        ("deploy/edge/install.py", "Install an edge"), ("deploy/edge/targets.py", "Apply an edge's targets to Warpgate")]
# Pages not generated here but linked from it: kept out of the staleness check.
LINK_ROOTS = ("README.md", "docs", "deploy", "CONTRIBUTING.md", "SECURITY.md", "CHANGELOG.md")


def load(name: str) -> dict:
    return yaml.safe_load((MODEL / name).read_text(encoding="utf-8")) or {}


def cell(v) -> str:
    """A table cell: one line, pipes escaped."""
    if isinstance(v, list):
        v = ", ".join(str(x) for x in v)
    return re.sub(r"\s+", " ", str(v if v is not None else "")).replace("|", "\\|").strip()


def table(head: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def components() -> str:
    cs = load("components.yaml")["components"]
    s = HEADER.format(src="model/components.yaml") + "# Components\n\nWhat ReliKey composes. Each is an upstream image " \
        "or binary pinned by version (and digest), configured only through its own documented interfaces (decision 0001).\n\n"
    for tier, title in (("core", "Core (once per organisation or site)"), ("edge", "Edge (next to the legacy system)"),
                        ("none", "Outside ReliKey")):
        rows = [[c["id"], c["name"], c.get("version", ""), c.get("licence", ""), c.get("zone", ""), c["role"]]
                for c in cs if c.get("tier") == tier]
        if rows:
            s += f"## {title}\n\n" + table(["id", "component", "version", "licence", "zone", "role"], rows) + "\n"
    pinned = [[c["id"], f"`{c['image']}:{c['version']}`", f"`{c['digest'][:19]}...`" if c.get("digest") else "not pinned yet"]
              for c in cs if c.get("image")]
    s += "## Images\n\n" + table(["id", "image", "digest"], pinned)
    return s


def contracts() -> str:
    ks = load("contracts.yaml")["contracts"]
    s = HEADER.format(src="model/contracts.yaml") + "# Contracts\n\nEvery seam between two components, what crosses it and " \
        "with which permission. Status: needed, built (code and unit tests), verified (an end-to-end test).\n\n"
    s += table(["id", "contract", "provider", "consumer", "status"],
               [[k["id"], k["name"], k["provider"], k["consumer"], k["status"]] for k in ks]) + "\n"
    for k in ks:
        s += f"## {k['id']}: {cell(k['name'])}\n\n- Provider: {cell(k['provider'])}; consumer: {cell(k['consumer'])}\n" \
             f"- Interface: {cell(k['api'])}\n- Permission: {cell(k['permission'])}\n- Status: {k['status']}\n"
        if k.get("keyclerk"):
            s += f"- KeyClerk: {cell(k['keyclerk'])}\n"
        s += f"\n{cell(k['behaviour'])}\n\n"
    return s


def flows() -> str:
    fs = load("flows.yaml")["flows"]
    s = HEADER.format(src="model/flows.yaml") + "# Flows and ports\n\nEvery connection ReliKey allows. Only the bastion " \
        "reaches the legacy zone, and the legacy system reaches only the facade (decision 0002); the core never connects " \
        "into an edge (decision 0005). A loopback flow stays on one host.\n\n"
    s += table(["id", "from", "to", "protocol", "port", "scope", "purpose"],
               [[f["id"], f["from"], f["to"], f["protocol"], f["port"], f.get("scope", "network"), f["purpose"]] for f in fs])
    return s


def patterns() -> str:
    ps = load("patterns.yaml")["patterns"]
    s = HEADER.format(src="model/patterns.yaml") + "# Access patterns\n\nHow a person reaches a legacy system, by what the " \
        "system can accept.\n\n"
    for p in ps:
        s += f"## {p['id']}: {cell(p['name'])}\n\n- When: {cell(p['when'])}\n- Path: {' -> '.join(p['path'])} " \
             f"(flows {', '.join(p['flows'])})\n- Governance: {cell(p['governance'])}\n- Evidence: {cell(p['evidence'])}\n"
        if p.get("residual"):
            s += f"- Residual: {cell(p['residual'])}\n"
        s += "\n"
    return s


def profiles() -> str:
    d = load("profiles.yaml")
    s = HEADER.format(src="model/profiles.yaml") + "# Profiles\n\nWhich product fills each role (decision 0016). The " \
        "reference profile is the one ReliKey is optimised for.\n\n"
    roles = sorted({r for p in d["profiles"] for r in p["bind"]})
    s += table(["profile"] + roles, [[p["id"] + (" (optimised)" if p.get("optimised") else "")] +
                                     [p["bind"].get(r, "") for r in roles] for p in d["profiles"]])
    return s


FIELD = re.compile(r'^(\s*)(\w+)\s+(?:struct\s*\{|[\w.*\[\]]+\s+`json:"([\w]+)"`)')


def agent_config() -> tuple[str, list[str]]:
    """agent.json's fields from the Config struct: the comment block above each field is its description."""
    src = AGENT_MAIN.read_text(encoding="utf-8").splitlines()
    start = next(i for i, ln in enumerate(src) if ln.startswith("type Config struct"))
    rows, missing, comment, stack = [], [], [], []
    for line in src[start + 1:]:
        t = line.strip()
        if t.startswith("}") and not stack:
            break
        if t.startswith("//"):
            comment.append(t[2:].strip())
            continue
        m = re.match(r'^\}\s*`json:"(\w+)"`', t)
        if m:
            stack.pop()
            continue
        nested = re.match(r'^(\w+)\s+struct\s*\{', t)
        if nested:
            # the struct's json name is on its closing line: read ahead
            depth, j = 0, src.index(line, start)
            for k in range(j, len(src)):
                depth += src[k].count("{") - src[k].count("}")
                if depth == 0:
                    name = re.search(r'`json:"(\w+)"`', src[k]).group(1)
                    break
            key = ".".join(stack + [name])
            rows.append([f"`{key}`", "object", " ".join(comment)])
            if not comment:
                missing.append(key)
            stack.append(name)
            comment = []
            continue
        f = re.match(r'^(\w+)\s+([\w.*\[\]]+)\s+`json:"(\w+)"`', t)
        if f:
            key = ".".join(stack + [f.group(3)])
            typ = {"string": "string", "*string": "string", "bool": "boolean", "int": "integer"}.get(f.group(2), "string")
            rows.append([f"`{key}`", typ, " ".join(comment)])
            if not comment:
                missing.append(key)
        comment = []
    s = HEADER.format(src="agent/cmd/relikey-agent/main.go (type Config)") + "# agent.json\n\nThe edge agent's " \
        "configuration (`relikey-agent run -config /etc/relikey/agent.json`). Unknown keys are refused, so a misspelt " \
        "setting never falls back to a default.\n\n" + table(["key", "type", "description"], rows)
    return s, missing


def cli() -> str:
    s = HEADER.format(src="each command's own --help and the agent's flag definitions") + "# Commands\n\n"
    s += "## relikey-agent\n\n"
    src = AGENT_MAIN.read_text(encoding="utf-8")
    for sub in re.finditer(r'flag\.NewFlagSet\("(\w+)"', src):
        body = src[sub.end():].split("flag.NewFlagSet(")[0]
        flags = re.findall(r'fs\.(?:String|Bool|Int|Duration|Int64)\("([\w-]+)",\s*([^,]+),\s*"([^"]*)"\)', body)
        s += f"### relikey-agent {sub.group(1)}\n\n"
        s += (table(["flag", "default", "meaning"], [[f"`-{n}`", d.strip(), m] for n, d, m in flags]) if flags
              else "No flags.\n") + "\n"
    for path, title in CLIS:
        out = subprocess.run([sys.executable, str(ROOT / path), "--help"], capture_output=True, text=True,
                             env={**os.environ, "COLUMNS": "120"}, cwd=ROOT)
        if out.returncode != 0:
            raise SystemExit(f"{path} --help failed ({out.returncode}): every installer must print its usage without "
                             f"a running stack\n{out.stderr[-400:]}")
        s += f"## {title}: `{path}`\n\n```text\n{help_text(out.stdout).rstrip()}\n```\n\n"
    doc = re.search(r'"""(.*?)"""', (ROOT / "deploy/core/realm.py").read_text(encoding="utf-8"), re.S).group(1)
    usage = "\n".join(ln for ln in doc.splitlines() if ln.strip().startswith("python realm.py"))
    s += f"## The broker's realm: `deploy/core/realm.py` (inside the core pod)\n\n```text\n{usage.strip()}\n```\n"
    return s


def help_text(text: str) -> str:
    """argparse --help in one form on every Python: before 3.13 an option with aliases repeats its metavar
    ('--a X, --b X'), from 3.13 it is named once at the end ('--a, --b X'). The page uses the newer form."""
    return re.sub(r"(-{1,2}[\w-]+) (\S+), (-{1,2}[\w-]+) \2\b", r"\1, \3 \2", text)


def crypto() -> str:
    """Decision 0022 A2: the cryptography on every link, in every format, behind every trust anchor."""
    d = load("crypto.yaml")
    fl = {f["id"]: f for f in load("flows.yaml")["flows"]}
    s = HEADER.format(src="model/crypto.yaml and model/flows.yaml") + "# Cryptography\n\nWhat protects each link, " \
        "each signed or encrypted format and each long-lived key, and its quantum status (decision 0022). Policy: " \
        "required = both ends are ReliKey's and a peer without the hybrid key exchange is refused; visible = hybrid " \
        "preferred, a classical fallback allowed and reported; record = the other end is not ReliKey's, what was " \
        "negotiated is recorded. Claims are tied to the pinned version they were checked for.\n\n"
    s += "## Links\n\n" + table(["link", "from", "to", "protocol", "key exchange", "policy", "ends", "note"],
                                [[fid, fl[fid]["from"], fl[fid]["to"], fl[fid]["protocol"], ln["kex"], ln["policy"],
                                  ln.get("ends", []), ln.get("note", "")] for fid, ln in d["links"].items() if fid in fl])
    s += "\n## Components\n\n" + table(["component", "version", "TLS server", "TLS client", "SSH", "how checked"],
                                      [[cid, c.get("version") or "", c.get("tls_server", ""), c.get("tls_client", ""),
                                        " / ".join(x for x in (c.get("ssh_server", ""), c.get("ssh_client", "")) if x),
                                        c["checked"]] for cid, c in d["components"].items()])
    s += "\n## Formats\n\n" + table(["format", "algorithm", "quantum", "owner", "plan"],
                                   [[name, f.get("signature") or f.get("encryption") or f.get("key_agreement"),
                                     f["quantum"], f["owner"], f["plan"]] for name, f in d["formats"].items()])
    s += "\n## Trust anchors\n\n" + table(["key", "algorithm", "custody", "pinned on", "quantum", "rotation"],
                                         [[name, a["algorithm"], a["custody"], a["pinned_on"], a["quantum"], a["rotation"]]
                                          for name, a in d["anchors"].items()])
    s += "\n## Residuals\n\n" + "".join(f"- {cell(r)}\n" for r in d["residuals"])
    return s


def cbom() -> str:
    """The same inventory as a CycloneDX 1.6 cryptography bill of materials (0021 point 3, 0022 A2). Deterministic:
    no timestamps or random serials, so the check can compare it like any generated page."""
    import json
    d = load("crypto.yaml")
    comps = []
    for name, f in d["formats"].items():
        algo = f.get("signature") or f.get("encryption") or f.get("key_agreement")
        comps.append({"type": "cryptographic-asset", "bom-ref": f"format:{name}", "name": name,
                      "cryptoProperties": {"assetType": "protocol", "protocolProperties": {"type": "other"}},
                      "properties": [{"name": "relikey:algorithm", "value": str(algo)},
                                     {"name": "relikey:quantum", "value": f["quantum"]},
                                     {"name": "relikey:owner", "value": f["owner"]}]})
    for name, a in d["anchors"].items():
        comps.append({"type": "cryptographic-asset", "bom-ref": f"key:{name}", "name": name,
                      "cryptoProperties": {"assetType": "related-crypto-material",
                                           "relatedCryptoMaterialProperties": {"type": "public-key"}},
                      "properties": [{"name": "relikey:algorithm", "value": a["algorithm"]},
                                     {"name": "relikey:quantum", "value": a["quantum"]},
                                     {"name": "relikey:custody", "value": a["custody"]}]})
    for fid, ln in d["links"].items():
        comps.append({"type": "cryptographic-asset", "bom-ref": f"link:{fid}", "name": f"link {fid}",
                      "cryptoProperties": {"assetType": "protocol", "protocolProperties": {"type": "tls"}},
                      "properties": [{"name": "relikey:kex", "value": ln["kex"]},
                                     {"name": "relikey:policy", "value": ln["policy"]}]})
    bom = {"bomFormat": "CycloneDX", "specVersion": "1.6", "version": 1,
           "metadata": {"component": {"type": "application", "name": "ReliKey", "bom-ref": "relikey"}},
           "components": comps}
    return json.dumps(bom, indent=1) + "\n"


def notice() -> str:
    """NOTICE, generated from model/components.yaml so the composed components and their licences cannot drift."""
    rows = [c for c in load("components.yaml")["components"] if c.get("image") and c.get("licence")]
    w = max(len(c["name"]) for c in rows)
    lines = [f"  {c['name']:<{w}} - {c['licence']:<10} - {c.get('upstream') or ''}".rstrip() for c in rows]
    return ("ReliKey\nLicensed under the European Union Public Licence v. 1.2 (EUPL-1.2, LICENSE).\n\n"
            "ReliKey composes, without modification, upstream images that keep their own licences. Each runs as its own\n"
            "container; ReliKey links none of them into its code:\n" + "\n".join(lines) + "\n\n"
            "Optional, not shipped: OpenBao (MPL-2.0, https://github.com/openbao/openbao), read by Warpgate when an\n"
            "organisation runs one.\n\n"
            "Generated by tools/docs.py from model/components.yaml.\n")


def pages() -> tuple[dict[str, str], list[str]]:
    cfg, missing = agent_config()
    return {"components.md": components(), "contracts.md": contracts(), "flows.md": flows(), "patterns.md": patterns(),
            "profiles.md": profiles(), "agent-config.md": cfg, "commands.md": cli(), "crypto.md": crypto(),
            "relikey-cbom.cdx.json": cbom(), "README.md": index()}, missing


